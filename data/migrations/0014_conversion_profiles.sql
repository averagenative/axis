-- ── History is never rewritten ────────────────────────────────────

CREATE FUNCTION conversion_profile_revision_kept() RETURNS trigger
	LANGUAGE plpgsql AS $$
BEGIN
	RAISE EXCEPTION 'a conversion profile revision is never changed or deleted'
		USING ERRCODE = 'restrict_violation';
END $$;

CREATE TRIGGER conversion_profile_revision_no_change BEFORE UPDATE OR DELETE ON conversion_profile_revision
	FOR EACH ROW EXECUTE FUNCTION conversion_profile_revision_kept();
CREATE TRIGGER conversion_profile_revision_no_truncate BEFORE TRUNCATE ON conversion_profile_revision
	FOR EACH STATEMENT EXECUTE FUNCTION conversion_profile_revision_kept();

-- A new revision is the next number of its profile, and a built-in's comes
-- from the code, a user's profile's from a user.
CREATE FUNCTION conversion_profile_revision_add() RETURNS trigger
	LANGUAGE plpgsql AS $$
DECLARE
	is_built_in boolean;
	last_number integer;
BEGIN
	SELECT built_in INTO is_built_in FROM conversion_profile WHERE id = NEW.profile_id FOR UPDATE;
	IF is_built_in AND NEW.origin <> 'code' THEN
		RAISE EXCEPTION 'a built-in profile is never edited' USING ERRCODE = 'check_violation';
	END IF;
	IF NOT is_built_in AND NEW.origin <> 'user' THEN
		RAISE EXCEPTION 'only a built-in profile has revisions from the code' USING ERRCODE = 'check_violation';
	END IF;
	SELECT coalesce(max(number), 0) INTO last_number FROM conversion_profile_revision
		WHERE profile_id = NEW.profile_id;
	IF NEW.number <> last_number + 1 THEN
		RAISE EXCEPTION 'revisions are numbered in order' USING ERRCODE = 'check_violation';
	END IF;
	RETURN NEW;
END $$;

CREATE TRIGGER conversion_profile_revision_numbered BEFORE INSERT ON conversion_profile_revision
	FOR EACH ROW EXECUTE FUNCTION conversion_profile_revision_add();

-- A profile is never deleted; what it is never changes; its current
-- revision only moves on, to one of its own.
CREATE FUNCTION conversion_profile_guard() RETURNS trigger
	LANGUAGE plpgsql AS $$
DECLARE
	old_number integer;
	new_number integer;
BEGIN
	IF TG_OP = 'DELETE' THEN
		RAISE EXCEPTION 'a conversion profile is archived, never deleted' USING ERRCODE = 'restrict_violation';
	END IF;
	IF NEW.slug <> OLD.slug OR NEW.kind <> OLD.kind OR NEW.built_in <> OLD.built_in
	   OR NEW.copied_from IS DISTINCT FROM OLD.copied_from OR NEW.created_at <> OLD.created_at OR NEW.id <> OLD.id THEN
		RAISE EXCEPTION 'what a conversion profile is never changes' USING ERRCODE = 'restrict_violation';
	END IF;
	IF NEW.current_revision_id IS DISTINCT FROM OLD.current_revision_id THEN
		IF NEW.current_revision_id IS NULL THEN
			RAISE EXCEPTION 'a profile keeps a current revision' USING ERRCODE = 'restrict_violation';
		END IF;
		SELECT number INTO new_number FROM conversion_profile_revision
			WHERE id = NEW.current_revision_id AND profile_id = NEW.id;
		IF new_number IS NULL THEN
			RAISE EXCEPTION 'the current revision is one of the profile''s own' USING ERRCODE = 'restrict_violation';
		END IF;
		IF OLD.current_revision_id IS NOT NULL THEN
			SELECT number INTO old_number FROM conversion_profile_revision WHERE id = OLD.current_revision_id;
			IF new_number <= old_number THEN
				RAISE EXCEPTION 'the current revision only moves on' USING ERRCODE = 'restrict_violation';
			END IF;
		END IF;
	END IF;
	RETURN NEW;
END $$;

CREATE TRIGGER conversion_profile_guarded BEFORE UPDATE OR DELETE ON conversion_profile
	FOR EACH ROW EXECUTE FUNCTION conversion_profile_guard();
CREATE TRIGGER conversion_profile_no_truncate BEFORE TRUNCATE ON conversion_profile
	FOR EACH STATEMENT EXECUTE FUNCTION conversion_profile_revision_kept();

-- A proof is never changed; a carried one comes from an earlier revision
-- of the same profile.
CREATE FUNCTION conversion_profile_proof_check() RETURNS trigger
	LANGUAGE plpgsql AS $$
BEGIN
	IF TG_OP = 'UPDATE' THEN
		RAISE EXCEPTION 'a proof is never changed' USING ERRCODE = 'restrict_violation';
	END IF;
	IF NEW.method = 'carried' AND NOT EXISTS (
		SELECT 1 FROM conversion_profile_revision a JOIN conversion_profile_revision b ON b.profile_id = a.profile_id
		WHERE a.id = NEW.carried_from AND b.id = NEW.revision_id AND a.number < b.number) THEN
		RAISE EXCEPTION 'a proof is carried only from an earlier revision of the same profile'
			USING ERRCODE = 'check_violation';
	END IF;
	RETURN NEW;
END $$;

CREATE TRIGGER conversion_profile_proof_checked BEFORE INSERT OR UPDATE ON conversion_profile_proof
	FOR EACH ROW EXECUTE FUNCTION conversion_profile_proof_check();

-- ── The estimates, by revision ────────────────────────────────────

-- Nothing is dropped: a row naming a target that is no built-in would stop
-- the migration (the code only ever wrote these seven).
DO $$
BEGIN
	IF EXISTS (SELECT 1 FROM estimate_fact f WHERE NOT EXISTS (SELECT 1 FROM conversion_profile p
	           WHERE p.slug = f.target AND p.built_in))
	   OR EXISTS (SELECT 1 FROM estimate_sample s WHERE NOT EXISTS (SELECT 1 FROM conversion_profile p
	           WHERE p.slug = s.target AND p.built_in)) THEN
		RAISE EXCEPTION 'an estimate names a target that is not a built-in profile';
	END IF;
END $$;

ALTER TABLE estimate_fact ADD COLUMN revision_id bigint
	REFERENCES conversion_profile_revision (id) ON DELETE RESTRICT;
UPDATE estimate_fact f SET revision_id = r.id
FROM conversion_profile p JOIN conversion_profile_revision r ON r.profile_id = p.id AND r.number = 1
WHERE p.slug = f.target AND p.built_in;
ALTER TABLE estimate_fact ALTER COLUMN revision_id SET NOT NULL;
ALTER TABLE estimate_fact DROP CONSTRAINT estimate_fact_pkey;
ALTER TABLE estimate_fact DROP CONSTRAINT estimate_fact_names;
ALTER TABLE estimate_fact DROP COLUMN target;
ALTER TABLE estimate_fact ADD PRIMARY KEY (snapshot_id, revision_id, report, dim);
ALTER TABLE estimate_fact ADD CONSTRAINT estimate_fact_names
	CHECK (report ~ '^[a-z][a-z0-9_]{0,40}$' AND octet_length(dim) <= 200);
CREATE INDEX estimate_fact_revision_idx ON estimate_fact (revision_id, snapshot_id);

-- What the old prediction read from the target, now on the sample.
ALTER TABLE estimate_sample
	ADD COLUMN revision_id bigint REFERENCES conversion_profile_revision (id) ON DELETE RESTRICT,
	ADD COLUMN out_bit_depth integer,
	ADD COLUMN nominal_bitrate integer,
	ADD COLUMN reduce_to_cd boolean NOT NULL DEFAULT false;
UPDATE estimate_sample s SET revision_id = r.id,
	out_bit_depth = CASE WHEN s.part = 'video' THEN
		CASE s.target WHEN 'balanced' THEN 8 WHEN 'max_compat' THEN 8 ELSE 10 END END,
	nominal_bitrate = CASE WHEN s.part = 'audio' THEN
		CASE s.target WHEN 'music_space_saver' THEN 128000 WHEN 'music_compat' THEN 245000
			WHEN 'audiobooks' THEN CASE WHEN s.channels = 1 THEN 32000 ELSE 48000 END ELSE 0 END END
FROM conversion_profile p JOIN conversion_profile_revision r ON r.profile_id = p.id AND r.number = 1
WHERE p.slug = s.target AND p.built_in;
ALTER TABLE estimate_sample ALTER COLUMN revision_id SET NOT NULL;
ALTER TABLE estimate_sample DROP CONSTRAINT estimate_sample_names;
ALTER TABLE estimate_sample DROP COLUMN target;
ALTER TABLE estimate_sample ADD CONSTRAINT estimate_sample_names CHECK (codec ~ '^[a-z0-9_]{1,32}$'
	AND family ~ '^[a-z]{1,16}$' AND source_codec ~ '^[a-z0-9_.-]{1,64}$');
ALTER TABLE estimate_sample ADD CONSTRAINT estimate_sample_output CHECK (
	(out_bit_depth IS NULL OR out_bit_depth IN (8, 10))
	AND (nominal_bitrate IS NULL OR nominal_bitrate BETWEEN 0 AND 10000000)
	AND (part <> 'video' OR out_bit_depth IS NOT NULL)
	AND (part <> 'audio' OR nominal_bitrate IS NOT NULL));
CREATE INDEX estimate_sample_revision_idx ON estimate_sample (revision_id, id);

