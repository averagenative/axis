-- 0014_conversion_profiles.sql - conversion profiles: immutable revisions,
-- proofs, assignments to library roots; the estimates keyed by revision
-- SPDX-License-Identifier: AGPL-3.0-or-later
--
-- A profile is a name and a kind; what it does is its current revision's
-- definition (src/transcode/axis-profile.h: one strict format, stored in its
-- canonical text with the SHA-256 of that text).  Every edit adds a
-- revision; nothing rewrites one:
--
--  - conversion_profile: the slug (a built-in's is reserved: a user's
--    profile is always custom_<id>), the kind, whether it is built in,
--    whether it is archived (hidden from choices, its record kept), and its
--    current revision.  Never deleted.
--  - conversion_profile_revision: never updated, never deleted (triggers;
--    and whatever refers to one holds it with ON DELETE RESTRICT besides).
--    A built-in's revisions are written by the daemon from its code table
--    (origin 'code'); a user's by an administrator (origin 'user').  The
--    daemon validates the definition whenever it reads one: a row that does
--    not validate (an older format, a damaged row) is unusable, shown as
--    such, and never repaired.
--  - conversion_profile_proof: a revision proven on real devices (the
--    canary step of a later change) or carrying the proof of the revision
--    it was made from (an edit that cannot change the bytes produced).  No
--    proof, locked.  This change writes only carried proofs, so nothing is
--    unlocked yet.  A carried proof goes when the one it came from does.
--  - conversion_profile_assignment: at most one video and one audio profile
--    per root.  It records intent only (and what the Savings and
--    Compatibility pages show for the root); assigning converts nothing.  A
--    verdict other than safe needs the administrator's confirmation.
--
-- The estimates (0010) were keyed by a built-in target's id; they are keyed
-- by profile revision now, and what is there is carried over to the first
-- revision of the built-in of that id (the same definition the target
-- had), not dropped.  Samples now carry what predicting them needs (the
-- output's bit depth, the nominal audio bitrate), so that one recorded for
-- any revision applies to every revision whose output is the same for its
-- cell.
--
-- The settings estimate.min_saving_video, estimate.min_saving_audio,
-- estimate.large_4k and estimate.small_4k are members of a profile now and
-- are removed: a value an administrator had changed is not carried over
-- (a copy of the built-in is how to change it).

CREATE TABLE conversion_profile (
	id                  bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	slug                text        NOT NULL,
	kind                text        NOT NULL,
	built_in            boolean     NOT NULL,
	archived            boolean     NOT NULL DEFAULT false,
	current_revision_id bigint,
	copied_from         bigint      REFERENCES conversion_profile (id) ON DELETE RESTRICT,
	created_at          timestamptz NOT NULL DEFAULT now(),

	CONSTRAINT conversion_profile_slug_unique UNIQUE (slug),
	CONSTRAINT conversion_profile_id_kind UNIQUE (id, kind),
	CONSTRAINT conversion_profile_kind_known CHECK (kind IN ('video', 'audio')),
	CONSTRAINT conversion_profile_slug_form CHECK (slug ~ '^[a-z][a-z0-9_]{0,40}$'),
	-- A user's profile is custom_<its id>; no built-in slug ever starts so,
	-- so a user's profile can never take one.
	CONSTRAINT conversion_profile_slug_reserved CHECK (CASE WHEN built_in THEN slug !~ '^custom_'
		ELSE slug = 'custom_' || id::text END),
	CONSTRAINT conversion_profile_builtin_kept CHECK (NOT (built_in AND archived))
);

CREATE TABLE conversion_profile_revision (
	id          bigint      GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
	profile_id  bigint      NOT NULL REFERENCES conversion_profile (id) ON DELETE RESTRICT,
	number      integer     NOT NULL,
	name        text        NOT NULL,
	note        text        NOT NULL DEFAULT '',
	definition  text        NOT NULL,
	hash        text        NOT NULL,
	origin      text        NOT NULL,
	created_by  text,
	created_at  timestamptz NOT NULL DEFAULT now(),

	CONSTRAINT conversion_profile_revision_number UNIQUE (profile_id, number),
	CONSTRAINT conversion_profile_revision_of UNIQUE (id, profile_id),
	CONSTRAINT conversion_profile_revision_number_positive CHECK (number >= 1),
	CONSTRAINT conversion_profile_revision_hash CHECK (hash = encode(sha256(convert_to(definition, 'UTF8')), 'hex')),
	CONSTRAINT conversion_profile_revision_size CHECK (octet_length(definition) <= 8192),
	CONSTRAINT conversion_profile_revision_name CHECK (char_length(name) BETWEEN 1 AND 80
		AND name !~ '[\x01-\x1f\x7f\u0080-\u009f]'),
	CONSTRAINT conversion_profile_revision_note CHECK (char_length(note) <= 500
		AND note !~ '[\x01-\x09\x0b-\x1f\x7f\u0080-\u009f]'),
	CONSTRAINT conversion_profile_revision_origin CHECK (origin IN ('code', 'user')
		AND (origin = 'code') = (created_by IS NULL))
);

ALTER TABLE conversion_profile ADD CONSTRAINT conversion_profile_current
	FOREIGN KEY (current_revision_id, id) REFERENCES conversion_profile_revision (id, profile_id)
	ON DELETE RESTRICT DEFERRABLE INITIALLY DEFERRED;

CREATE TABLE conversion_profile_proof (
	revision_id  bigint      PRIMARY KEY REFERENCES conversion_profile_revision (id) ON DELETE RESTRICT,
	proven_at    timestamptz NOT NULL DEFAULT now(),
	-- 'canary': confirmed on devices (a later change writes these);
	-- 'carried': from the revision it was made from.
	method       text        NOT NULL,
	carried_from bigint      REFERENCES conversion_profile_proof (revision_id) ON DELETE CASCADE,
	recorded_by  text,

	CONSTRAINT conversion_profile_proof_method CHECK (method IN ('canary', 'carried')
		AND (method = 'carried') = (carried_from IS NOT NULL))
);

CREATE TABLE conversion_profile_assignment (
	root_id     bigint      NOT NULL REFERENCES library_root (id) ON DELETE CASCADE,
	kind        text        NOT NULL,
	profile_id  bigint      NOT NULL,
	-- The revision that was current when it was assigned (what was shown).
	revision_id bigint      NOT NULL,
	verdict     text        NOT NULL,
	confirmed   boolean     NOT NULL DEFAULT false,
	assigned_by text        NOT NULL,
	assigned_at timestamptz NOT NULL DEFAULT now(),

	PRIMARY KEY (root_id, kind),
	CONSTRAINT conversion_profile_assignment_profile FOREIGN KEY (profile_id, kind)
		REFERENCES conversion_profile (id, kind) ON DELETE RESTRICT,
	CONSTRAINT conversion_profile_assignment_revision FOREIGN KEY (revision_id, profile_id)
		REFERENCES conversion_profile_revision (id, profile_id) ON DELETE RESTRICT,
	CONSTRAINT conversion_profile_assignment_verdict CHECK (verdict IN ('safe', 'risky', 'unknown')
		AND (verdict = 'safe' OR confirmed))
);

CREATE INDEX conversion_profile_assignment_profile_idx ON conversion_profile_assignment (profile_id);

