-- 0022_quality_profiles.sql - quality profiles: which releases of a title
-- are acceptable, in what order, at what size, and when an upgrade is worth
-- taking
-- SPDX-License-Identifier: AGPL-3.0-or-later
--
-- A profile is a name and a definition (src/quality/axis-quality.h: one
-- strict JSON format, stored in its canonical text, with the format it is in
-- in a column of its own).  The daemon reads every definition through the
-- one strict reader: a row that does not validate (a damaged row, or one a
-- newer version wrote in a later format) is unusable, refused whole and shown
-- with why; nothing repairs it and nothing uses half of it.
--
--  - The built-ins are written here and again at every start from the code
--    table (axis_quality_store_sync_builtins()), so a built-in whose code
--    changed is brought up to date.  Nothing else writes one: a person
--    copies it.  A built-in is never deleted.
--  - A user's profile is custom_<id>.  It is deleted only when nothing uses
--    it: the store asks every module that refers to profiles (and the
--    default-profile setting) first, and the modules' own tables refer to
--    this one with ON DELETE RESTRICT besides.
--  - revision counts the saves, so that an edit made from an older one is
--    refused rather than silently overwriting a newer one.

CREATE TABLE quality_profile (
	id          bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	slug        text        NOT NULL,
	name        text        NOT NULL,
	built_in    boolean     NOT NULL,
	format      integer     NOT NULL,
	definition  text        NOT NULL,
	revision    integer     NOT NULL DEFAULT 1,
	copied_from bigint      REFERENCES quality_profile (id) ON DELETE SET NULL,
	created_at  timestamptz NOT NULL DEFAULT now(),
	updated_at  timestamptz NOT NULL DEFAULT now(),
	updated_by  text,

	CONSTRAINT quality_profile_slug_unique UNIQUE (slug),
	CONSTRAINT quality_profile_slug_form CHECK (slug ~ '^[a-z][a-z0-9_]{0,40}$'),
	-- A user's profile is custom_<its id>; no built-in slug ever starts so.
	CONSTRAINT quality_profile_slug_reserved CHECK (CASE WHEN built_in THEN slug !~ '^custom_'
		ELSE slug = 'custom_' || id::text END),
	CONSTRAINT quality_profile_name CHECK (char_length(name) BETWEEN 1 AND 80
		AND name !~ '[\x01-\x1f\x7f\u0080-\u009f]'),
	CONSTRAINT quality_profile_size CHECK (octet_length(definition) <= 16384),
	-- A JSON object that says its format, the one in the column.
	CONSTRAINT quality_profile_json CHECK (jsonb_typeof(definition::jsonb) = 'object'
		AND (definition::jsonb -> 'format') = to_jsonb(format)),
	CONSTRAINT quality_profile_format CHECK (format >= 1),
	CONSTRAINT quality_profile_revision CHECK (revision >= 1),
	CONSTRAINT quality_profile_updated_by CHECK (updated_by IS NULL OR char_length(updated_by) BETWEEN 1 AND 200)
);

