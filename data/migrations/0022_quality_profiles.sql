-- ── What a profile is never changes; a built-in is never deleted ─────

CREATE FUNCTION quality_profile_guard() RETURNS trigger
	LANGUAGE plpgsql AS $$
BEGIN
	IF TG_OP = 'DELETE' THEN
		IF OLD.built_in THEN
			RAISE EXCEPTION 'a built-in quality profile is never deleted' USING ERRCODE = 'restrict_violation';
		END IF;
		RETURN OLD;
	END IF;
	IF NEW.id <> OLD.id OR NEW.slug <> OLD.slug OR NEW.built_in <> OLD.built_in OR NEW.created_at <> OLD.created_at
	   OR (NEW.copied_from IS DISTINCT FROM OLD.copied_from AND NEW.copied_from IS NOT NULL) THEN
		RAISE EXCEPTION 'what a quality profile is never changes' USING ERRCODE = 'restrict_violation';
	END IF;
	IF NEW.revision < OLD.revision THEN
		RAISE EXCEPTION 'a quality profile''s revision only moves on' USING ERRCODE = 'restrict_violation';
	END IF;
	RETURN NEW;
END $$;

CREATE TRIGGER quality_profile_guarded BEFORE UPDATE OR DELETE ON quality_profile
	FOR EACH ROW EXECUTE FUNCTION quality_profile_guard();

CREATE FUNCTION quality_profile_no_truncate() RETURNS trigger
	LANGUAGE plpgsql AS $$
BEGIN
	RAISE EXCEPTION 'quality profiles are not truncated' USING ERRCODE = 'restrict_violation';
END $$;

CREATE TRIGGER quality_profile_kept BEFORE TRUNCATE ON quality_profile
	FOR EACH STATEMENT EXECUTE FUNCTION quality_profile_no_truncate();
